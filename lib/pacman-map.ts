// Reusing same tile size for compatibility
export const TILE_SIZE = 20;
export const BOARD_WIDTH = MAPS[0][0].length * TILE_SIZE;
export const BOARD_HEIGHT = MAPS[0].length * TILE_SIZE;

export type TileType = "WALL" | "DOT" | "POWER" | "EMPTY" | "GATE" | "PRIZE";

export function createGrid(stage: number = 1): { type: TileType; eaten: boolean }[][] {
  const mapIndex = (stage - 1) % MAPS.length;
  const selectedMap = MAPS[mapIndex];
  
  return selectedMap.map((row) =>
    row.split("").map((char) => {
      let type: TileType = "EMPTY";
      if (char === "W") type = "WALL";
      if (char === ".") type = "DOT";
      if (char === "o") type = "POWER";
      if (char === "=") type = "GATE";
      if (char === "P") type = "PRIZE";
      return { type, eaten: false };
    })
  );
}

